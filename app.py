@app.route(
    "/login",
    methods=["GET", "POST"]
)
def login():

    if request.method == "POST":

        email = request.form.get(
            "email",
            ""
        ).strip()

        password = request.form.get(
            "password",
            ""
        )


        connection = get_db()

        try:

            user = connection.execute(
                """
                SELECT *
                FROM users
                WHERE email = %s
                """,
                (email,)
            ).fetchone()

        finally:

            connection.close()


        if user and check_password_hash(
            user["password"],
            password
        ):

            session["user_id"] = user["id"]

            session["user_name"] = user["name"]

            session["user_email"] = user["email"]

            session["user_role"] = user["role"]


            # Admin

            if user["role"] == "admin":

                return redirect(
                    url_for(
                        "admin_dashboard"
                    )
                )


            # Student

            return redirect(
                url_for(
                    "dashboard"
                )
            )


        flash(
            "Invalid email or password.",
            "error"
        )

        return redirect(
            url_for("login")
        )


    return render_template(
        "login.html"
    )


