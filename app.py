@app.route(
    "/delete-note/<int:note_id>"
)
def delete_note(note_id):

    if "user_id" not in session:

        return redirect(
            url_for("login")
        )


    if session.get(
        "user_role"
    ) != "admin":

        flash(
            "Only admin can delete notes.",
            "error"
        )

        return redirect(
            url_for("dashboard")
        )


    connection = get_db()

    try:

        note = connection.execute(
            """
            SELECT id
            FROM notes
            WHERE id = %s
            """,
            (note_id,)
        ).fetchone()


        if note:

            connection.execute(
                """
                DELETE FROM notes
                WHERE id = %s
                """,
                (note_id,)
            )

            connection.commit()

            flash(
                "Note deleted successfully.",
                "success"
            )

        else:

            flash(
                "Note not found.",
                "error"
            )

    finally:

        connection.close()


    return redirect(
        url_for("admin_dashboard")
    )


