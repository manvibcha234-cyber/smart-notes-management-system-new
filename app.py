@app.route(
    "/download/<int:note_id>"
)
def download(note_id):

    if "user_id" not in session:

        return redirect(
            url_for("login")
        )


    connection = get_db()

    try:

        note = connection.execute(
            """
            SELECT
                filename,
                file_data
            FROM notes
            WHERE id = %s
            """,
            (note_id,)
        ).fetchone()

    finally:

        connection.close()


    if not note:

        flash(
            "Note not found.",
            "error"
        )

        return redirect(
            url_for("notes")
        )


    if not note["file_data"]:

        flash(
            "PDF file is not available.",
            "error"
        )

        return redirect(
            url_for("notes")
        )


    return send_file(
        io.BytesIO(note["file_data"]),
        mimetype="application/pdf",
        as_attachment=True,
        download_name=note["filename"]
    )


