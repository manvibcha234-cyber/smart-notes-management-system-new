@app.route("/notes")
def notes():

    if "user_id" not in session:

        return redirect(
            url_for("login")
        )


    search = request.args.get(
        "search",
        ""
    ).strip()


    connection = get_db()

    try:

        if search:

            search_pattern = f"%{search}%"


            notes_data = connection.execute(
                """
                SELECT
                    id,
                    title,
                    subject,
                    category,
                    filename,
                    uploaded_by
                FROM notes

                WHERE title ILIKE %s
                   OR subject ILIKE %s
                   OR category ILIKE %s

                ORDER BY id DESC
                """,
                (
                    search_pattern,
                    search_pattern,
                    search_pattern
                )
            ).fetchall()


        else:

            notes_data = connection.execute(
                """
                SELECT
                    id,
                    title,
                    subject,
                    category,
                    filename,
                    uploaded_by
                FROM notes
                ORDER BY id DESC
                """
            ).fetchall()

    finally:

        connection.close()


    return render_template(
        "notes.html",

        notes=notes_data,

        search=search
    )


