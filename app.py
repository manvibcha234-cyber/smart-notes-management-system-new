@app.route(
    "/upload-note",
    methods=["POST"]
)
def upload_note():

    if "user_id" not in session:

        return redirect(
            url_for("login")
        )


    if session.get(
        "user_role"
    ) != "admin":

        flash(
            "Only admin can upload notes.",
            "error"
        )

        return redirect(
            url_for("dashboard")
        )


    title = request.form.get(
        "title",
        ""
    ).strip()


    subject = request.form.get(
        "subject",
        ""
    ).strip()


    category = request.form.get(
        "category",
        ""
    ).strip()


    file = request.files.get(
        "file"
    )


    # Empty field check

    if not title or not subject or not category:

        flash(
            "Please fill all note details.",
            "error"
        )

        return redirect(
            url_for("admin_dashboard")
        )


    # File check

    if not file or file.filename == "":

        flash(
            "Please select a PDF file.",
            "error"
        )

        return redirect(
            url_for("admin_dashboard")
        )


    # PDF check

    if not allowed_file(
        file.filename
    ):

        flash(
            "Only PDF files are allowed.",
            "error"
        )

        return redirect(
            url_for("admin_dashboard")
        )


    # Safe filename

    filename = secure_filename(
        file.filename
    )


    # =====================================================
    # READ PDF INTO MEMORY
    # =====================================================

    file_data = file.read()


    if not file_data:

        flash(
            "The selected PDF is empty.",
            "error"
        )

        return redirect(
            url_for("admin_dashboard")
        )


    # =====================================================
    # SAVE PDF + DETAILS IN POSTGRESQL
    # =====================================================

    connection = get_db()

    try:

        connection.execute(
            """
            INSERT INTO notes
            (
                title,
                subject,
                category,
                filename,
                uploaded_by,
                file_data
            )

            VALUES (%s, %s, %s, %s, %s, %s)
            """,
            (
                title,
                subject,
                category,
                filename,
                session["user_name"],
                psycopg.Binary(file_data)
            )
        )


        connection.commit()


        flash(
            "Notes uploaded successfully!",
            "success"
        )


    except Exception:

        connection.rollback()

        flash(
            "Error while uploading note.",
            "error"
        )


    finally:

        connection.close()


    return redirect(
        url_for("admin_dashboard")
    )


